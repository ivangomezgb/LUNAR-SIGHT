"""Download the NAIF generic SPICE kernels used by the pipeline and write kernels/lln.tm.

Run from anywhere:  python pipeline/scripts/download_kernels.py  [--force]

Kernels (https://naif.jpl.nasa.gov/pub/naif/generic_kernels/):
  lsk/naif0012.tls                 leap seconds
  spk/planets/de440s.bsp           planetary ephemeris DE440 (short, 1849-2150)
  pck/pck00011.tpc                 body constants / IAU orientation
  pck/moon_pa_de440_200625.bpc     high-precision lunar orientation (MOON_PA_DE440)
  fk/satellites/moon_de440_250416.tf  lunar frames: MOON_PA / MOON_ME aliases for DE440

The kernel binaries are gitignored; only lln.tm is versioned. lln.tm uses a PATH_VALUES
entry; ephem.py loads it after chdir'ing into kernels/ so the relative "." always works.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import requests

BASE = "https://naif.jpl.nasa.gov/pub/naif/generic_kernels/"
KERNELS = [
    "lsk/naif0012.tls",
    "spk/planets/de440s.bsp",
    "pck/pck00011.tpc",
    "pck/moon_pa_de440_200625.bpc",
    "fk/satellites/moon_de440_250416.tf",
]
KERNEL_DIR = Path(__file__).resolve().parents[1] / "kernels"

META_TEMPLATE = """KPL/MK

   Lunar Landing Site Navigator meta-kernel.
   Generated by pipeline/scripts/download_kernels.py.
   PATH_VALUES is '.', so load it with the working directory set to
   pipeline/kernels (lln.ephem.load_kernels() does this for you).

   moon_de440_250416.tf defines MOON_PA_DE440 / MOON_ME_DE440_ME421 and aliases
   the generic names MOON_PA and MOON_ME to them.

\\begindata

   PATH_VALUES  = ( '.' )
   PATH_SYMBOLS = ( 'K' )

   KERNELS_TO_LOAD = (
{entries}
   )

\\begintext
"""


def write_meta(kdir: Path = KERNEL_DIR) -> Path:
    entries = "\n".join(f"      '$K/{Path(k).name}'" for k in KERNELS)
    tm = kdir / "lln.tm"
    tm.write_text(META_TEMPLATE.format(entries=entries), encoding="ascii", newline="\n")
    return tm


def download(force: bool = False, kdir: Path = KERNEL_DIR) -> None:
    kdir.mkdir(parents=True, exist_ok=True)
    for rel in KERNELS:
        dest = kdir / Path(rel).name
        if dest.exists() and dest.stat().st_size > 0 and not force:
            print(f"ok    {dest.name} ({dest.stat().st_size / 1e6:.1f} MB)")
            continue
        url = BASE + rel
        print(f"get   {url}")
        tmp = dest.with_suffix(dest.suffix + ".part")
        with requests.get(url, stream=True, timeout=120) as r:
            r.raise_for_status()
            with open(tmp, "wb") as f:
                for chunk in r.iter_content(1 << 20):
                    f.write(chunk)
        tmp.replace(dest)
        print(f"saved {dest.name} ({dest.stat().st_size / 1e6:.1f} MB)")
    print(f"wrote {write_meta(kdir)}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--force", action="store_true", help="re-download existing files")
    ap.add_argument("--meta-only", action="store_true", help="only rewrite lln.tm")
    a = ap.parse_args()
    if a.meta_only:
        print(write_meta())
    else:
        download(a.force)
    sys.exit(0)
